CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (length(btrim(name)) > 0),
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT users_email_normalized CHECK (email = lower(btrim(email)))
);
CREATE TABLE areas (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (id,user_id)
);
CREATE TABLE competencies (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (id,user_id)
);
CREATE TABLE routines (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL CHECK (length(btrim(name)) > 0),
    description TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (id,user_id)
);
CREATE TABLE goals (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title VARCHAR(150) NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL CHECK (end_date >= start_date),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (id,user_id)
);
CREATE TABLE tasks (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,

    area_id BIGINT NOT NULL,
    routine_id BIGINT,
    goal_id BIGINT,
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    task_date DATE NOT NULL,
    task_time TIME,
    priority VARCHAR(30) NOT NULL CHECK (length(btrim(priority)) > 0),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    UNIQUE (id,user_id),
    CONSTRAINT tasks_area_owner FOREIGN KEY (area_id,user_id) REFERENCES areas(id,user_id) ON DELETE RESTRICT,
    CONSTRAINT tasks_routine_owner FOREIGN KEY (routine_id,user_id) REFERENCES routines(id,user_id) ON DELETE RESTRICT,
    CONSTRAINT tasks_goal_owner FOREIGN KEY (goal_id,user_id) REFERENCES goals(id,user_id) ON DELETE RESTRICT,
    CONSTRAINT tasks_completion_consistent CHECK (completed = (completed_at IS NOT NULL))
);
CREATE TABLE task_competencies (
    task_id BIGINT NOT NULL,
    competency_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    PRIMARY KEY (task_id,competency_id),
    CONSTRAINT task_competencies_task_owner FOREIGN KEY (task_id,user_id) REFERENCES tasks(id,user_id) ON DELETE CASCADE,
    CONSTRAINT task_competencies_competency_owner FOREIGN KEY (competency_id,user_id) REFERENCES competencies(id,user_id) ON DELETE RESTRICT
);
CREATE INDEX areas_owner_idx ON areas(user_id);
CREATE INDEX competencies_owner_idx ON competencies(user_id);
CREATE INDEX routines_owner_idx ON routines(user_id);
CREATE INDEX goals_owner_idx ON goals(user_id);
CREATE INDEX tasks_owner_date_idx ON tasks(user_id,task_date);
CREATE INDEX tasks_area_idx ON tasks(area_id,user_id);
CREATE INDEX tasks_routine_idx ON tasks(routine_id,user_id);
CREATE INDEX tasks_goal_idx ON tasks(goal_id,user_id);
CREATE INDEX task_competencies_competency_idx ON task_competencies(competency_id,user_id);
CREATE INDEX task_competencies_owner_idx ON task_competencies(user_id);

-- Serialize changes to a task's competency set, including direct SQL.
CREATE FUNCTION lock_competency_parent() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        PERFORM id FROM tasks WHERE id IN (OLD.task_id,NEW.task_id) ORDER BY id FOR UPDATE;
    ELSIF TG_OP = 'DELETE' THEN
        PERFORM id FROM tasks WHERE id = OLD.task_id FOR UPDATE;
    ELSE
        PERFORM id FROM tasks WHERE id = NEW.task_id FOR UPDATE;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER lock_competency_parent BEFORE INSERT OR UPDATE OR DELETE ON task_competencies
FOR EACH ROW EXECUTE FUNCTION lock_competency_parent();

CREATE FUNCTION require_task_competency() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE task_to_check BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'tasks' THEN task_to_check := NEW.id;
    ELSE task_to_check := OLD.task_id;
    END IF;
    IF EXISTS (SELECT 1 FROM tasks WHERE id = task_to_check)
       AND NOT EXISTS (SELECT 1 FROM task_competencies WHERE task_id = task_to_check) THEN
        RAISE EXCEPTION 'A task requires at least one competency'
            USING ERRCODE = '23514', CONSTRAINT = 'tasks_min_one_competency';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER tasks_min_one_competency AFTER INSERT OR UPDATE ON tasks
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION require_task_competency();
CREATE CONSTRAINT TRIGGER links_min_one_competency AFTER DELETE OR UPDATE ON task_competencies
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION require_task_competency();
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'jarvis_app') THEN
        REVOKE ALL ON flyway_schema_history FROM jarvis_app;
    END IF;
END $$;
